    def do_POST(self):
        rota = urlparse(self.path).path
        try: dados = self.ler_json()
        except Exception: self.enviar_json({"erro": "Dados invalidos."}, 400); return

        if rota == "/api/cadastro":
            nome = str(dados.get("nome", "")).strip(); matricula = str(dados.get("matricula", "")).strip()
            turma = str(dados.get("turma", "")).strip(); senha = str(dados.get("senha", ""))
            if not nome or not matricula or not turma: self.enviar_json({"erro": "Preencha nome, matricula e turma."}, 400); return
            if not matricula.isdigit() or not 6 <= len(matricula) <= 12: self.enviar_json({"erro": "A matricula deve ter de 6 a 12 numeros."}, 400); return
            if len(senha) < 8: self.enviar_json({"erro": "A senha precisa ter pelo menos 8 caracteres."}, 400); return
            try:
                with conectar() as conexao:
                    conexao.execute("INSERT INTO alunos (nome, matricula, turma, senha_hash) VALUES (%s, %s, %s, %s)",
                                    (nome, matricula, turma, gerar_hash_senha(senha)))
            except IntegrityError:
                self.enviar_json({"erro": "Essa matricula ja esta cadastrada."}, 409); return
            self.enviar_json({"mensagem": "Cadastro realizado com sucesso!"}, 201); return

        if rota == "/api/login":
            matricula = str(dados.get("matricula", "")).strip(); senha = str(dados.get("senha", ""))
            with conectar() as conexao:
                aluno = conexao.execute("SELECT id_aluno, nome, matricula, turma, senha_hash FROM alunos WHERE matricula = %s", (matricula,)).fetchone()
            if not aluno or not verificar_senha(senha, aluno["senha_hash"]): self.enviar_json({"erro": "Matricula ou senha incorretas."}, 401); return
            token = criar_sessao("aluno", aluno["id_aluno"])
            cookie = f"{COOKIE_ALUNO}={token}; Path=/; Max-Age=604800; HttpOnly; SameSite=Lax; Secure"
            self.enviar_json({"mensagem": "Login realizado com sucesso!", "aluno": {"id": aluno["id_aluno"], "nome": aluno["nome"], "matricula": aluno["matricula"], "turma": aluno["turma"]}}, cookies=[cookie]); return

        if rota == "/api/logout-aluno":
            token = self.ler_cookies().get(COOKIE_ALUNO)
            encerrar_sessao(token)
            cookie = f"{COOKIE_ALUNO}=; Path=/; Max-Age=0; HttpOnly; SameSite=Lax; Secure"
            self.enviar_json({"mensagem": "Sessao encerrada."}, cookies=[cookie]); return

        if rota == "/api/aluno/emprestimos":
            aluno = self.obter_aluno_logado()
            if not aluno:
                self.enviar_json({"erro": "Faca login para solicitar um emprestimo."}, 401)
                return
            id_livro = int(dados.get("id_livro") or 0)
            if not id_livro:
                self.enviar_json({"erro": "Selecione um livro valido."}, 400)
                return
            with conectar() as conexao:
                exemplar = conexao.execute("""
                    SELECT ex.id_exemplar, l.titulo
                    FROM exemplares ex
                    JOIN livros l ON l.id_livro = ex.id_livro
                    WHERE ex.id_livro = %s AND ex.status = 'disponivel'
                    ORDER BY ex.id_exemplar
                    LIMIT 1 FOR UPDATE OF ex
                """, (id_livro,)).fetchone()
                if not exemplar:
                    self.enviar_json({"erro": "Nenhum exemplar disponivel deste livro no momento."}, 409)
                    return
                conexao.execute(
                    "INSERT INTO emprestimos (id_aluno, id_exemplar, status) "
                    "VALUES (%s, %s, 'solicitado')",
                    (aluno["id"], exemplar["id_exemplar"]),
                )
                conexao.execute(
                    "UPDATE exemplares SET status = 'reservado' WHERE id_exemplar = %s",
                    (exemplar["id_exemplar"],),
                )
            self.enviar_json({
                "mensagem": f"Solicitacao de '{exemplar['titulo']}' enviada! Aguarde a aprovacao do bibliotecario."
            }, 201)
            return

        if rota == "/api/aluno/emprestimos/devolucao":
            aluno = self.obter_aluno_logado()
            if not aluno: self.enviar_json({"erro": "Faca login primeiro."}, 401); return
            id_emprestimo = int(dados.get("id_emprestimo") or 0)
            if not id_emprestimo: self.enviar_json({"erro": "Emprestimo invalido."}, 400); return
            with conectar() as conexao:
                emp = conexao.execute("SELECT id_emprestimo, data_devolucao, data_solicitacao_devolucao FROM emprestimos WHERE id_emprestimo = %s AND id_aluno = %s", (id_emprestimo, aluno["id"])).fetchone()
                if not emp: self.enviar_json({"erro": "Emprestimo nao encontrado."}, 404); return
                if emp["data_devolucao"]: self.enviar_json({"erro": "Este livro ja foi devolvido."}, 409); return
                if emp["data_solicitacao_devolucao"]: self.enviar_json({"erro": "A devolucao deste livro ja foi solicitada."}, 409); return
                status_atual = conexao.execute(
                    "SELECT status FROM emprestimos WHERE id_emprestimo = %s AND id_aluno = %s",
                    (id_emprestimo, aluno["id"]),
                ).fetchone()
                if not status_atual or status_atual["status"] != "emprestado":
                    self.enviar_json({"erro": "A devolucao so pode ser solicitada depois da retirada do livro."}, 409)
                    return
                conexao.execute(
                    "UPDATE emprestimos SET status = 'devolucao_solicitada', data_solicitacao_devolucao = %s "
                    "WHERE id_emprestimo = %s AND data_devolucao IS NULL",
                    (datetime.now(timezone.utc), id_emprestimo),
                )
            self.enviar_json({"mensagem": "Solicitacao de devolucao enviada! Entregue o livro ao bibliotecario para confirmar."}); return

        if rota == "/api/login-bibliotecario":
            usuario = str(dados.get("usuario", "")).strip(); senha = str(dados.get("senha", ""))
            if not USUARIO_BIBLIOTECARIO or not SENHA_BIBLIOTECARIO:
                self.enviar_json({"erro": "A conta do bibliotecario ainda nao foi configurada no servidor."}, 503); return
            if not (hmac.compare_digest(usuario.casefold(), USUARIO_BIBLIOTECARIO.casefold()) and hmac.compare_digest(senha, SENHA_BIBLIOTECARIO)):
                self.enviar_json({"erro": "Usuario ou senha incorretos."}, 401); return
            token = criar_sessao("bibliotecario")
            cookie = f"{COOKIE_BIBLIOTECARIO}={token}; Path=/; Max-Age=604800; HttpOnly; SameSite=Lax; Secure"
            self.enviar_json({"mensagem": "Acesso liberado."}, cookies=[cookie]); return

        if rota == "/api/logout-bibliotecario":
            token = self.ler_cookies().get(COOKIE_BIBLIOTECARIO)
            encerrar_sessao(token)
            cookie = f"{COOKIE_BIBLIOTECARIO}=; Path=/; Max-Age=0; HttpOnly; SameSite=Lax; Secure"
            self.enviar_json({"mensagem": "Sessao encerrada."}, cookies=[cookie]); return

