class Linha(dict):
    """Linha que aceita acesso por nome da coluna e por posição, como sqlite3.Row."""
    def __getitem__(self, chave):
        if isinstance(chave, int):
            return list(self.values())[chave]
        return super().__getitem__(chave)


def fabrica_linha(cursor):
    descricao = cursor.description or ()
    nomes = [coluna.name for coluna in descricao]
    return lambda valores: Linha(zip(nomes, valores))


class ConexaoPostgres:
    """Pequena camada de compatibilidade para manter as rotas existentes."""
    def __init__(self, conexao):
        self._conexao = conexao

    def __enter__(self):
        return self

    def __exit__(self, tipo, valor, traceback):
        if tipo:
            self._conexao.rollback()
        else:
            self._conexao.commit()
        self._conexao.close()
        return False

    def execute(self, sql, parametros=()):
        cursor = self._conexao.cursor(row_factory=fabrica_linha)
        cursor.execute(sql, parametros)
        return cursor


def conectar():
    if not DATABASE_URL:
        raise RuntimeError("A variável DATABASE_URL não foi configurada no Render.")
    # prepare_threshold=None evita prepared statements incompatíveis com o pooler
    # em modo transaction do Supabase.
    conexao = psycopg.connect(
        DATABASE_URL,
        connect_timeout=15,
        prepare_threshold=None,
        application_name="techbook-render",
    )
    return ConexaoPostgres(conexao)


def iniciar_banco():
    """Confere a conexão e a presença das cinco tabelas já criadas no Supabase."""
    obrigatorias = {"alunos", "bibliotecarios", "livros", "exemplares", "emprestimos"}
    with conectar() as conexao:
        linhas = conexao.execute(
            "SELECT table_name FROM information_schema.tables "
            "WHERE table_schema = 'public' AND table_type = 'BASE TABLE'"
        ).fetchall()
    existentes = {linha["table_name"] for linha in linhas}
    faltando = obrigatorias - existentes
    if faltando:
        raise RuntimeError(
            "Faltam tabelas no Supabase: " + ", ".join(sorted(faltando))
        )

    # Sessões no banco sobrevivem a reinicializações do Render.
    with conectar() as conexao:
        conexao.execute("""
            CREATE TABLE IF NOT EXISTS public.techbook_sessoes (
                id_sessao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                token_hash TEXT NOT NULL UNIQUE,
                tipo VARCHAR(20) NOT NULL
                    CHECK (tipo IN ('aluno', 'bibliotecario')),
                id_usuario BIGINT,
                criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                expira_em TIMESTAMPTZ NOT NULL
            )
        """)
        conexao.execute("""
            CREATE INDEX IF NOT EXISTS idx_techbook_sessoes_expira
            ON public.techbook_sessoes (expira_em)
        """)
        conexao.execute("ALTER TABLE public.techbook_sessoes ENABLE ROW LEVEL SECURITY")
        conexao.execute("DELETE FROM public.techbook_sessoes WHERE expira_em <= NOW()")


def hash_token(token):
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def criar_sessao(tipo, id_usuario=None):
    token = secrets.token_urlsafe(32)
    expira_em = datetime.now(timezone.utc) + timedelta(days=7)
    with conectar() as conexao:
        conexao.execute(
            "INSERT INTO public.techbook_sessoes (token_hash, tipo, id_usuario, expira_em) "
            "VALUES (%s, %s, %s, %s)",
            (hash_token(token), tipo, id_usuario, expira_em),
        )
    return token


def encerrar_sessao(token):
    if not token:
        return
    with conectar() as conexao:
        conexao.execute(
            "DELETE FROM public.techbook_sessoes WHERE token_hash = %s",
            (hash_token(token),),
        )


def gerar_hash_senha(senha):
    sal = secrets.token_hex(16)
    chave = hashlib.pbkdf2_hmac(
        "sha256", senha.encode("utf-8"), sal.encode("utf-8"), 100_000
    ).hex()
    return f"{sal}${chave}"


def verificar_senha(senha, senha_salva):
    if not senha_salva or "$" not in senha_salva:
        return False
    sal, chave_original = senha_salva.split("$", 1)
    chave_nova = hashlib.pbkdf2_hmac(
        "sha256", senha.encode("utf-8"), sal.encode("utf-8"), 100_000
    ).hex()
    return hmac.compare_digest(chave_nova, chave_original)


def normalizar_status(valor):
    return str(valor or "").strip().lower().replace("í", "i")


class ServidorTechBook(SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=PASTA_PROJETO, **kwargs)

    def log_message(self, format, *args):
        print(f"[TechBook] {self.address_string()} - {format % args}")

    def enviar_json(self, dados, status=200, cookies=None):
        corpo = json.dumps(dados, ensure_ascii=False, default=str).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(corpo)))
        self.send_header("Cache-Control", "no-store")
        if cookies:
            for cookie in cookies:
                self.send_header("Set-Cookie", cookie)
        self.end_headers()
        self.wfile.write(corpo)

    def redirecionar(self, destino):
        self.send_response(302)
        self.send_header("Location", destino)
        self.end_headers()

    def ler_json(self):
        tamanho = int(self.headers.get("Content-Length", "0"))
        if tamanho > 100_000:
            raise ValueError("Envio grande demais.")
        if tamanho == 0:
            return {}
        return json.loads(self.rfile.read(tamanho).decode("utf-8"))

    def ler_cookies(self):
        bruto = self.headers.get("Cookie")
        if not bruto:
            return {}
        jarra = SimpleCookie()
        jarra.load(bruto)
        return {nome: item.value for nome, item in jarra.items()}

    def obter_aluno_logado(self):
        token = self.ler_cookies().get(COOKIE_ALUNO)
        if not token:
            return None
        with conectar() as conexao:
            aluno = conexao.execute(
                """SELECT a.id_aluno, a.nome, a.matricula, a.turma
                   FROM public.techbook_sessoes s
                   JOIN alunos a ON a.id_aluno = s.id_usuario
                   WHERE s.token_hash = %s AND s.tipo = 'aluno'
                     AND s.expira_em > NOW()""",
                (hash_token(token),),
            ).fetchone()
        if not aluno:
            return None
        return {"id": aluno["id_aluno"], "nome": aluno["nome"],
                "matricula": aluno["matricula"], "turma": aluno["turma"]}

    def obter_bibliotecario_logado(self):
        token = self.ler_cookies().get(COOKIE_BIBLIOTECARIO)
        if not token:
            return False
        with conectar() as conexao:
            sessao = conexao.execute(
                """SELECT 1 FROM public.techbook_sessoes
                   WHERE token_hash = %s AND tipo = 'bibliotecario'
                     AND expira_em > NOW()""",
                (hash_token(token),),
            ).fetchone()
        return bool(sessao)

